//! Regenerate `src/fold_tables.rs` (compatibility decompositions and combining classes)
//! from the `unicode-normalization` crate's data:
//! `cargo run --release --example gen_fold_tables > src/fold_tables.rs`
use std::fmt::Write;

fn main() {
    let mut decomp: Vec<(u32, Vec<u32>)> = Vec::new();
    let mut ccc: Vec<(u32, u8)> = Vec::new();
    for cp in 0u32..=0x10FFFF {
        let Some(c) = char::from_u32(cp) else { continue };
        // Hangul syllables decompose by formula (see `fold.rs`).
        if (0xAC00..=0xD7A3).contains(&cp) {
            continue;
        }
        let mut d = Vec::new();
        unicode_normalization::char::decompose_compatible(c, |x| d.push(x as u32));
        if d != [cp] {
            decomp.push((cp, d));
        }
        let k = unicode_normalization::char::canonical_combining_class(c);
        if k != 0 {
            ccc.push((cp, k));
        }
    }
    // Characters whose folded form doesn't depend on their neighbours: no kept (non-
    // diacritic) combining mark in their decomposition. `FOLD` maps those to their folded
    // bytes when that differs from the character; anything else is `SLOW`.
    let diacritic = |c: char| matches!(c, '\u{300}'..='\u{36F}' | '\u{1AB0}'..='\u{1AFF}' | '\u{1DC0}'..='\u{1DFF}' | '\u{20D0}'..='\u{20FF}' | '\u{FE20}'..='\u{FE2F}');
    let fold_one = |c: char| -> Vec<u8> {
        let mut out = Vec::new();
        let mut buf = [0u8; 4];
        let mut d = Vec::new();
        unicode_normalization::char::decompose_compatible(c, |x| d.push(x));
        for x in d {
            if diacritic(x) { continue; }
            for l in x.to_lowercase() {
                match l {
                    'ß' => out.extend_from_slice(b"ss"),
                    'ς' => out.extend_from_slice('σ'.encode_utf8(&mut buf).as_bytes()),
                    l if diacritic(l) => {}
                    l => out.extend_from_slice(l.encode_utf8(&mut buf).as_bytes()),
                }
            }
        }
        out
    };
    let mut fold: Vec<(u32, Vec<u8>)> = Vec::new();
    let mut slow: Vec<u32> = Vec::new();
    for cp in 0x80u32..=0x10FFFF {
        let Some(c) = char::from_u32(cp) else { continue };
        let mut d = Vec::new();
        unicode_normalization::char::decompose_compatible(c, |x| d.push(x));
        let kept_mark = d.iter().any(|&x| unicode_normalization::char::canonical_combining_class(x) != 0 && !diacritic(x));
        if kept_mark {
            slow.push(cp);
            continue;
        }
        let f = fold_one(c);
        if f != c.to_string().into_bytes() {
            fold.push((cp, f));
        }
    }
    let mut out = String::new();
    writeln!(out, "//! Generated by `examples/gen_fold_tables.rs` from Unicode {:?} data. Don't edit.", unicode_normalization::UNICODE_VERSION).unwrap();
    writeln!(out, "//!").unwrap();
    writeln!(out, "//! `DECOMP`: (code point, start, length) into `DATA`, the full compatibility").unwrap();
    writeln!(out, "//! decomposition (NFKD, before reordering). `CCC`: non-zero combining classes.").unwrap();
    writeln!(out, "//! `FOLD`: characters folded on their own, into `FOLD_BYTES`; `SLOW`: characters that").unwrap();
    writeln!(out, "//! need the full decomposition and reordering (kept combining marks).").unwrap();
    writeln!(out).unwrap();
    let mut data: Vec<u32> = Vec::new();
    writeln!(out, "pub static DECOMP: [(u32, u32, u8); {}] = [", decomp.len()).unwrap();
    for (cp, d) in &decomp {
        writeln!(out, "    (0x{cp:X}, {}, {}),", data.len(), d.len()).unwrap();
        data.extend(d);
    }
    writeln!(out, "];\n").unwrap();
    writeln!(out, "pub static DATA: [u32; {}] = [", data.len()).unwrap();
    for chunk in data.chunks(12) {
        let line: Vec<String> = chunk.iter().map(|x| format!("0x{x:X}")).collect();
        writeln!(out, "    {},", line.join(", ")).unwrap();
    }
    writeln!(out, "];\n").unwrap();
    let mut bytes: Vec<u8> = Vec::new();
    writeln!(out, "pub static FOLD: [(u32, u32, u8); {}] = [", fold.len()).unwrap();
    for (cp, f) in &fold {
        writeln!(out, "    (0x{cp:X}, {}, {}),", bytes.len(), f.len()).unwrap();
        bytes.extend(f);
    }
    writeln!(out, "];\n").unwrap();
    writeln!(out, "pub static FOLD_BYTES: [u8; {}] = [", bytes.len()).unwrap();
    for chunk in bytes.chunks(20) {
        let line: Vec<String> = chunk.iter().map(|x| format!("{x}")).collect();
        writeln!(out, "    {},", line.join(", ")).unwrap();
    }
    writeln!(out, "];\n").unwrap();
    writeln!(out, "pub static SLOW: [u32; {}] = [", slow.len()).unwrap();
    for chunk in slow.chunks(12) {
        let line: Vec<String> = chunk.iter().map(|x| format!("0x{x:X}")).collect();
        writeln!(out, "    {},", line.join(", ")).unwrap();
    }
    writeln!(out, "];\n").unwrap();
    writeln!(out, "pub static CCC: [(u32, u8); {}] = [", ccc.len()).unwrap();
    for (cp, k) in &ccc {
        writeln!(out, "    (0x{cp:X}, {k}),").unwrap();
    }
    writeln!(out, "];").unwrap();
    print!("{out}");
}
